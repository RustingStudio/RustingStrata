# Extract the trellis codebook of the Gyro types (TQ2_T, TQK6, TQK7) from agentionai's llama.cpp fork into Rust.
# Usage: python -I tools/gen_tq_lut.py <fork>/ggml/src/ggml-common-tq.h > src/quant/tq_lut.rs
import re
import sys

src = open(sys.argv[1]).read()
body = re.search(r"tq_lut_f16\[4096\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
vals = re.findall(r"0x[0-9a-fA-F]{4}", body)
assert len(vals) == 4096, len(vals)
print("// Generated by tools/gen_tq_lut.py from ggml-common-tq.h of agentionai's llama.cpp fork (MIT License). Do not edit.")
print("#![cfg_attr(rustfmt, rustfmt_skip)]")
print("/// 2048 points of two values, as f16 bits: point i is (TQ_LUT_F16[2 i], TQ_LUT_F16[2 i + 1]).")
print(f"pub static TQ_LUT_F16: [u16; 4096] = [{', '.join(vals)}];")
